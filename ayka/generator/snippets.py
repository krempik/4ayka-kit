def _out_fields(res: ResourceSpec, spec: ProjectSpec) -> List[str]:
    out = ["    id: int"]
    if spec.auth and not res.public:
        out.append("    owner_id: Optional[int] = None")
    for f in res.fields:
        if f.name in ("id", "owner_id"):
            continue
        typ = _PYD[f.kind]
        out.append(f"    {f.name}: Optional[{typ}] = None")
    out.append("    created_at: Optional[datetime] = None")
    out.append("    updated_at: Optional[datetime] = None")
    return out


def _create_fields(res: ResourceSpec) -> List[str]:
    out = []
    for f in res.fields:
        if f.name in ("id", "owner_id", "created_at", "updated_at"):
            continue
        typ = _PYD[f.kind]
        if f.kind == "password":
            typ = "str"
        out.append(f"    {f.name}: {typ}{_PYD_DEFAULT.get(f.kind, '')}")
    return out


def schemas_code(spec: ProjectSpec) -> str:
    parts = ['''# Auto-generated by ayka-kit. Edit freely.
from datetime import datetime, date
from typing import Optional, List, Any
from pydantic import BaseModel, ConfigDict
''']
    for res in spec.resources.values():
        cls = class_name(res.name)

        def build(mode: str) -> str:
            header = (
                f"class {cls}Create(BaseModel):"
                if mode == "create"
                else f"class {cls}Update(BaseModel):\n    model_config = ConfigDict()"
            )
            if mode == "create":
                fields = _create_fields(res)
            else:
                fields = []
                for f in res.fields:
                    if f.name in ("id", "owner_id", "created_at", "updated_at"):
                        continue
                    typ = _PYD[f.kind]
                    fields.append(f"    {f.name}: Optional[{typ}] = None")
                if not fields:
                    fields = ["    pass"]
            return header + N + N.join(fields)

        parts.append(build("create"))
        parts.append(N)
        parts.append(build("update"))
        parts.append(N)

        out = [f"class {cls}Out(BaseModel):"]
        out.append("    model_config = ConfigDict(from_attributes=True)")
        out.extend(_out_fields(res, spec))
        parts.append(N.join(out))
        parts.append(N)

        if spec.auth and not res.public:
            parts.append(f"class {cls}OutAdmin({cls}Out):")
            parts.append("    pass")
            parts.append(N)
    return N.join(parts)


