def models_code(spec: ProjectSpec) -> str:
    parts = ['''# Auto-generated by ayka-kit. Edit freely.
from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Text, DateTime, Boolean, Float, Date, JSON, ForeignKey
from app.database import Base

def _utcnow():
    return datetime.now(timezone.utc)
''']
    if spec.auth:
        parts.append(_models_user(spec))
        parts.append(N)
    for res in spec.resources.values():
        parts.append(f"class {class_name(res.name)}(Base):")
        parts.append(f"    __tablename__ = {res.table!r}")
        for line in _model_body(res, spec):
            parts.append(line)
        parts.append(N)
    return N.join(parts)


