def _resource_endpoint_defs(res: ResourceSpec, spec: ProjectSpec) -> List[str]:
    cls = class_name(res.name)
    table_var = f"models.{cls}"
    owned = spec.auth and not res.public
    out = []
    user_dep = ", user=Depends(CURRENT_USER)" if owned else ""
    owner_filter = f".filter({table_var}.owner_id == user.id)" if owned else ""

    def scope(query):
        return query if not owned else f"{query}{owner_filter}"

    def check_owner(code: str) -> str:
        return code

    def not_found_guard(var: str) -> str:
        if owned:
            return f"    if not {var} or {var}.owner_id != user.id:\n        raise HTTPException(404, 'Not found')"
        return f"    if not {var}:\n        raise HTTPException(404, 'Not found')"

    crud = res.crud
    if crud in ("read", "write", "full"):
        out.append(f"@router.get('', response_model=list[schemas.{cls}Out])")
        out.append(f"def list_{res.name}(q: Optional[str] = Query(None), limit: int = Query(50, le=200), offset: int = 0{user_dep}, db: Session = Depends(get_db)):")
        out.append(f"    query = db.query({table_var}){owner_filter}")
        if res.search:
            fields = ", ".join(repr(f) for f in res.search)
            out.append("    if q:")
            out.append(f"        conds = [getattr({table_var}, f).like('%' + q + '%') for f in [{fields}]]")
            out.append("        query = query.filter(or_(*conds))")
        out.append(f"    return query.order_by({table_var}.created_at.desc()).offset(offset).limit(limit).all()")
        out.append(N)

    if crud in ("read", "full"):
        out.append(f"@router.get('/{{item_id}}', response_model=schemas.{cls}Out)")
        out.append(f"def get_{res.name}(item_id: int{user_dep}, db: Session = Depends(get_db)):")
        out.append(f"    item = db.query({table_var}).filter({table_var}.id == item_id).first()")
        out.append(not_found_guard("item"))
        out.append("    return item")
        out.append(N)

    if crud in ("create", "write", "full"):
        out.append(f"@router.post('', response_model=schemas.{cls}Out, status_code=201)")
        out.append(f"def create_{res.name}(payload: schemas.{cls}Create{user_dep}, db: Session = Depends(get_db)):")
        if owned:
            out.append(f"    item = {table_var}(owner_id=user.id, **payload.model_dump())")
        else:
            out.append(f"    item = {table_var}(**payload.model_dump())")
        out.append("    db.add(item)")
        out.append("    db.commit()")
        out.append("    db.refresh(item)")
        out.append("    return item")
        out.append(N)

    if crud in ("write", "full"):
        out.append(f"@router.put('/{{item_id}}', response_model=schemas.{cls}Out)")
        out.append(f"def update_{res.name}(item_id: int, payload: schemas.{cls}Update{user_dep}, db: Session = Depends(get_db)):")
        out.append(f"    item = db.query({table_var}).filter({table_var}.id == item_id).first()")
        out.append(not_found_guard("item"))
        out.append("    data = payload.model_dump(exclude_unset=True)")
        out.append("    for key, value in data.items():")
        out.append("        setattr(item, key, value)")
        out.append("    db.commit()")
        out.append("    db.refresh(item)")
        out.append("    return item")
        out.append(N)

        out.append(f"@router.delete('/{{item_id}}', status_code=204)")
        out.append(f"def delete_{res.name}(item_id: int{user_dep}, db: Session = Depends(get_db)):")
        out.append(f"    item = db.query({table_var}).filter({table_var}.id == item_id).first()")
        out.append(not_found_guard("item"))
        out.append("    db.delete(item)")
        out.append("    db.commit()")
        out.append("    return None")
    return out


def routes_code(spec: ProjectSpec) -> str:
    parts = ['''# Auto-generated by ayka-kit. Edit freely.
from typing import Optional, List, Dict, Any
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from sqlalchemy import or_
from app.database import get_db
from app import models, schemas
''']

    if spec.auth:
        parts.append(f'''from ayka.auth import JwtAuth, get_current_user_dependency

AUTH = JwtAuth(
    models.User,
    get_db,
    issuer={spec.name!r},
    secret_env={env_key(spec.name, 'SECRET')!r},
    secret_file='.secret_key',
)
CURRENT_USER = get_current_user_dependency(AUTH)

routers = [AUTH.build_router()]
''')
    else:
        parts.append("\nrouters = []\n")

    for res in spec.resources.values():
        parts.append(f"router = APIRouter(prefix='/api/{res.name}', tags=[{res.name!r}])")
        parts.append(N)
        parts.extend(_resource_endpoint_defs(res, spec))
        parts.append("routers.append(router)")
        parts.append(N)

    parts.append("\n__all__ = ['routers']\n")
    return N.join(parts)


