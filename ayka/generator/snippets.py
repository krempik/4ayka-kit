def _model_body(res: ResourceSpec, spec: ProjectSpec) -> List[str]:
    lines = ["    id = Column(Integer, primary_key=True, index=True)"]
    for f in res.fields:
        if f.name in ("id", "owner_id", "created_at", "updated_at"):
            continue
        lines.append(f"    {f.name} = {_COLUMN[f.kind](f)}")
    if spec.auth and not res.public:
        lines.append(f"    owner_id = Column(Integer, ForeignKey('users.id', ondelete='CASCADE'), index=True)")
    lines.append("    created_at = Column(DateTime, default=_utcnow, index=True)")
    lines.append("    updated_at = Column(DateTime, default=_utcnow, onupdate=_utcnow)")
    return lines


