def _test_payload(res: ResourceSpec) -> str:
    parts = []
    for f in res.fields:
        if f.kind in ("list",):
            parts.append(f"'{f.name}': []")
        elif f.kind == "bool":
            parts.append(f"'{f.name}': True")
        elif f.kind == "int":
            parts.append(f"'{f.name}': 1")
        elif f.kind == "float":
            parts.append(f"'{f.name}': 1.0")
        elif f.kind == "date":
            parts.append(f"'{f.name}': '2026-01-01'")
        elif f.kind == "datetime":
            parts.append(f"'{f.name}': '2026-01-01T00:00:00'")
        elif f.kind == "json":
            parts.append(f"'{f.name}': {{}}")
        else:
            parts.append(f"'{f.name}': 'x'")
    return ", ".join(parts)


