def class_name(name: str) -> str:
    return "".join(p.title() for p in name.replace("-", "_").split("_"))


def env_key(project_name: str, suffix: str) -> str:
    base = project_name.upper().replace("-", "_")
    return f"{base}_{suffix}"


# SQLAlchemy column snippet per field kind
_COLUMN = {
    "string": lambda f: f"Column(String(255))",
    "text": lambda f: f"Column(Text)",
    "int": lambda f: f"Column(Integer)",
    "float": lambda f: f"Column(Float)",
    "bool": lambda f: f"Column(Boolean, default=False)",
    "date": lambda f: f"Column(Date)",
    "datetime": lambda f: f"Column(DateTime)",
    "json": lambda f: f"Column(JSON)",
    "list": lambda f: f"Column(JSON)",
    "password": lambda f: f"Column(String(256))",
}

# Pydantic type snippet per field kind
_PYD = {
    "string": "str",
    "text": "str",
    "int": "int",
    "float": "float",
    "bool": "bool",
    "date": "date",
    "datetime": "datetime",
    "json": "Any",
    "list": "List[str]",
    "password": "str",
}

_PYD_DEFAULT = {
    "list": " = []",
    "bool": " = False",
}

N = "\n"


