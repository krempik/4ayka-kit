"""Code generation: turns a ProjectSpec into working FastAPI application files.

Each `..._code(spec, ...)` returns the full text of a generated file. The
generator is intentional and small: models -> schemas -> routers -> main, plus
run/config/CI scaffolding. Everything is plain AST-free text so users can diff
and hand-edit the output.
"""
